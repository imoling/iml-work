// 子智能体的纯逻辑：配额闸、事件转发闸、系统词。
//
// 单独成文件的理由与 skill-router-core / web-search-core 一致——agent-subagent.ts 要 import
// core-tools/llm（进而拉起 electron），整个文件在单测里跑不起来；而这里的三条规则恰恰是
// **错了不会报错、只会悄悄出事**的那种：
//   · 配额闸漏了 → 模型可以无限派子智能体，账单事故；
//   · 事件闸漏了 turn_end → 界面在主分身还在干活时显示"已完成"；
//   · 系统词漏了真实性纪律 → 子智能体编的内容会被主分身当事实转述给用户。
// 所以它们必须能被单测钉住，不能埋在依赖 electron 的模块里。
import type { CoreEvent } from '../shared/core-protocol'

/** 单个子智能体的墙钟上限。 */
export const SINGLE_BUDGET_MS = 120_000
/** 一轮主任务里所有子智能体的**总**墙钟预算。 */
export const TOTAL_BUDGET_MS = 240_000
/** 一轮主任务最多派几个。4 个覆盖「三个竞品 + 一个综述」这类形态已足够。 */
export const MAX_SUBAGENTS = 4
/** 子智能体的推理轮数上限（父是 14；子做聚焦子任务，8 轮足够且能压住成本）。 */
export const MAX_ITERATIONS = 8
/** 剩余预算低于这个数就不值得再起一个（起来也只够跑一两步，白花钱）。 */
const MIN_USEFUL_MS = 20_000

export type QuotaVerdict = { ok: true; budgetMs: number } | { ok: false; reason: string }

/**
 * 配额闸：还能不能再派一个子智能体。
 *
 * 拒绝时给的 reason 会**原样回灌给模型**，所以必须带上「那你该怎么办」——
 * 只说"不行"的话，模型会换个措辞把同一个请求再发一遍（实测过的模型行为），
 * 白白烧掉剩下的推理轮数。
 */
export function checkQuota(spawned: number, usedMs: number): QuotaVerdict {
  if (spawned >= MAX_SUBAGENTS) {
    return {
      ok: false,
      reason: `已达本次任务能分出的小分身上限（${MAX_SUBAGENTS} 个），不能再分了。`
        + '请用你自己的工具完成剩余调查，或基于小分身已带回的结论作答。',
    }
  }
  const left = TOTAL_BUDGET_MS - usedMs
  if (left < MIN_USEFUL_MS) {
    return {
      ok: false,
      reason: '小分身的总时间预算已用尽，不能再分了。请基于已经拿到的结论作答，'
        + '或用你自己的工具补最关键的那一两项，不要再拆子任务。',
    }
  }
  return { ok: true, budgetMs: Math.min(SINGLE_BUDGET_MS, left) }
}

/**
 * 子智能体的事件要不要转发给渲染层。
 *
 * 拦掉的两类都是**会污染主分身展示态**的：
 * ① 一轮任务的边界事件（turn_start/turn_end/interrupted）——渲染层对 turn_start 直接重置成空态、
 *    对 turn_end 收尾并停掉转圈。子智能体跑完就发一个 turn_end 的话，用户看到的是任务
 *    刚开始就显示"已完成"，而主分身其实才做到第二步。子智能体的边界由 agent_started/
 *    agent_finished 表达，不借用主任务的。
 * ② todo_updated——执行计划是主分身的，子智能体的内部清单不能覆盖它。
 */
export function shouldForwardSubEvent(type: CoreEvent['type']): boolean {
  return type !== 'turn_start' && type !== 'turn_end' && type !== 'interrupted' && type !== 'todo_updated'
}

/**
 * 委派规则——每轮随 ephemeral 上下文下发（只在本轮真的挂了 run_subagent 时）。
 *
 * 为什么工具的 description 不够（实测教训）：首版只把「什么时候用」写在工具描述里，
 * 结果「分别调查 workbuddy、dumate、loomy 三个产品」这句话，模型**自己正确拆成了三个调查面**，
 * 却仍然一个个串行 web_search 跑了 8 次、73 秒——它压根没想起工具表里有这个东西。
 * 工具描述只在模型**已经打算用它**时才起作用（决定怎么传参），不负责让它想起来。
 *
 * 判据必须**可数**：「要分别查几个对象」而不是「任务复不复杂」。
 * 这条是 TODO_RULE 验证过的经验——用形容词描述判据，模型的主观判断永远够不着门槛。
 */
export const SUBAGENT_RULE = `【任务拆分 · 小分身】
你可以**分出小分身**替你干活（run_subagent）——你是它们的老板，它们查完把结论交回给你。
需要**分别调查 2 个以上互不依赖的对象**（几个产品/公司/地区/时间段，每个都要单独查一遍）时，
**先用 todo_write 列出计划，紧接着把它们一次全部分出去**（会并行跑），不要自己一个一个搜、也不要一个一个分。
判据是「要分别查几个对象」，不是「难不难」。
为什么：每个小分身有自己**独立的上下文**，能读完十几篇资料再提炼结论带回来；而你自己串着搜，
读到第三个对象时前两个的正文早被挤出上下文了，最后只能给一份看着完整、其实很浅的对比。
分出去之后你负责汇总、对比、给结论——这才是你该花上下文的地方。
**跟用户说话时就叫它们「小分身」**，别说"子智能体""agent"这类词。`

/**
 * 并列调查的点名提示。
 *
 * 与技能的 triggerHint 同一形态：**不是硬路由**，只是在明显场景下点一句，模型保留否决权
 *（对象之间真有依赖时它可以不拆）。正则刻意收得很窄——必须同时命中「分别/各自」与
 * 「调查/对比」两组词，宁可漏也不要在普通问答里冒出一句莫名其妙的提示。
 */
export function subagentHint(content: string): string {
  const t = content || ''
  if (!/分别|各自|逐一|逐个|挨个/.test(t)) return ''
  if (!/调查|调研|查一下|查查|了解|对比|比较|分析|摸一下/.test(t)) return ''
  return '【提示】用户这句话要求**分别**调查多个对象——这正是 run_subagent 的用途：'
    + '给每个对象分一个小分身独立去查（它们各自能读完十几篇再提炼），比你自己一个个搜更深。'
    + '除非这些对象之间存在依赖（后一个要用到前一个的结果），否则**列完计划就一次全部分出去**，不要先自己搜一轮。'
}

/**
 * 小分身的系统词。全部要点都压在「你的输出会被本体直接引用」这一句上。
 *
 * 用户侧的称呼统一成「小分身 / 本体」（技术上仍是 subagent，见文件头）——
 * 模型会照着系统词的用语写实时叙述，而那句叙述是直接展示给用户看的。
 */
export function buildSubagentPrompt(task: string): string {
  return `你是工作分身分出来的一个**小分身**，只负责一件事：把交给你的这件事查清楚，把结论带回给分身本体。

【输出纪律】
- 你的回答会被本体**直接引用**，不面向最终用户：不要寒暄、不要说"好的我来查"、不要复述任务。
- 直接给**结论 + 关键证据**（数据、日期、出处链接）。能用列表就列表，不要铺陈成文章。
- 控制在 800 字以内。查到的原文不要整段搬运，提炼成事实陈述。

【真实性 · 红线】
- 只报工具**真实返回**的内容。查不到就明确写「未查到」，并说明你查了什么、缺什么。
- 严禁编造任何数据、人名、金额、日期、单号、链接。你编的内容会被本体当事实写进给用户的答复，
  比你自己胡说更危险——因为用户看不到你这一层。

【你的处境】
- 你**无法向用户提问**（用户看不见你，只看得见本体）。信息不足就如实写进结论，由本体去问。
- 你的步数与时间都有限。一个方向查两次还查不到就换检索词或换来源，不要在同一处反复打转。

【交给你的事】
${task}`
}

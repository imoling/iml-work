// 任务意图判断（纯正则，零依赖）——**主进程与渲染层共用**。
//
// 为什么必须放 shared：新旧两条执行链路都要用它决定分流。
// 只在主进程 skill-orchestrator 里判过一次，结果新内核那条路（turn:send-message）完全绕过它，
// 用户开着新内核让做 PPT，跑完一堆检索后模型只能说"当前环境无法导出，请自己复制到 WPS"（实测）。

/**
 * 「生成交付物」意图：要产出 .pptx / .docx / .xlsx 这类**文件**。
 *
 * 命中就该交给技能链路——真正能写出文件的是 pptx/docx/xlsx 技能（沙箱里跑 python-pptx 等），
 * 通用执行内核的工具表里没有"写文件"这个能力。
 *
 * 两个容易踩的细节（都是实测踩出来的）：
 * ① 必须带 i 标志——用户打「做个汇报PPT」（大写）不加 i 整条正则就不匹配；
 * ② 动词与宾语之间要留够间隔——「生成一份本月的费用统计表格」中间隔了 9 个字。
 */
export function wantsGeneratedFile(content: string): boolean {
  return /(生成|制作|导出|新建|做一?[份个]|写一?[份个]|整理成|汇总成|转成|排版成|做成|输出成)[^。！？\n]{0,12}(文档|word|docx|表格|excel|xlsx|ppt|pptx|幻灯|演示|报告|海报|pdf|文件|材料)/i.test(content)
}
